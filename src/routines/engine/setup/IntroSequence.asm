IntroSequence:						; the power-on animation: the EA Sports logo from its sprites
									; (EALogoESprite, EALogoASprite, SportsWordSprite, ElectronicWordSprite
									; ...), run by tasks until they end
	jsl.l Multi5Bios
	jsl.l ReadMenuPads
	ldx.w #IntroSoundList>>16
	lda.w #IntroSoundList&$FFFF
	jsl.l LoadSounds
	lda.w #IntroMode7Hook
	ldx.w #IntroMode7Hook>>16
	jsl.l SetNMIHook
	jsl.l InitTasks
	stz.b d0+2
	lda.b PadRaw1
	jsr.w CheckIntroMirrorButtons
	lda.b PadRaw2
	jsr.w CheckIntroMirrorButtons
	lda.b PadRaw3
	jsr.w CheckIntroMirrorButtons
	lda.b PadRaw4
	jsr.w CheckIntroMirrorButtons
	lda.b PadRaw5
	jsr.w CheckIntroMirrorButtons
	jsl.l SetupMode7Screen
	lda.w #$7FFF
	jsl.l SetBackdropColour
	lda.b $08
	sta.b a0+2
	lda.w #$0021
	jsl.l CreateSprite
	stx.b a0
	lda.w #$0066
	ldy.w #$0043
	jsr.w PositionIntroSprite
	jsl.l AnimateSprites
	jsl.l MarkWorkBuf
	lda.b $08
	sta.b a1+2
	lda.w #$0022
	jsl.l CreateSprite
	stx.b a1
	lda.w #$009F
	ldy.w #$0043
	jsr.w PositionIntroSprite
	jsl.l AnimateSprites
	jsl.l MarkWorkBuf
	lda.b $08
	sta.b a2+2
	lda.w #$0023
	jsl.l CreateSprite
	stx.b a2
	lda.w #$0080
	ldy.w #$007C
	jsr.w PositionIntroSprite
	jsl.l AnimateSprites
	jsl.l MarkWorkBuf
	lda.b $08
	sta.b a3+2
	lda.w #$0024
	jsl.l CreateSprite
	stx.b a3
	lda.w #$0080
	ldy.w #$0094
	jsr.w PositionIntroSprite
	jsl.l AnimateSprites
	jsl.l MarkWorkBuf
	lda.w #$0025
	jsl.l CreateSprite
	stx.b $7B
	lda.w #$0080
	ldy.w #$00B4
	jsr.w PositionIntroSprite
	jsl.l MarkWorkBuf
	lda.w #$0010
	sta.w introTM
	jsl.l AnimateSprites
	lda.w #OAMBuf+$1FF
	sta.b $28
	lda.w #OAMHighBytes
	sta.b $2A
	jsl.l BuildSpriteOAM
	jsl.l PackOAMHigh
	jsl.l WaitTransfers
	lda.w #$F254
	sta.b d3
	ldx.b a0
	ldy.b a0+2
	jsr.w PrepareIntroMode7Sprite
	lda.w #IntroStartALogo
	ldx.w #IntroStartALogo>>16
	ldy.w #$0001
	clc
	jsl.l StartTasks
	jsl.l AddStartKeyTask
	lda.w #IntroSoundCue1
	ldx.w #IntroSoundCue1>>16
	ldy.w #$F000
	jsl.l AddTask
	lda.b a0
	ldx.w #$0001
	jsr.w StartIntroScaleTask
	stz.w fadein
.loop:								; loop: call RunTasks, if TasksDone = 0 go to .loop, go to ClearNMIHook
	jsl.l RunTasks
	lda.w TasksDone
	beq .loop
	jml.l ClearNMIHook
