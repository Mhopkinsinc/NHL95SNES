PrintGoalieStatHeads:				; prints the goalie stats headings (Goalies, the column titles)
	ldx.w #TxtGoalies&$FFFF
	ldy.w #$0008
	jsl.l PrintItalicLeft
	lda.w #$0020
	sta.b $CF
	ldx.w #TxtBPlayers&$FFFF
	ldy.w #$0019
	jsl.l PrintBoldLeft
	lda.w #$0010
	sta.b $CF
	ldx.w #TxtGoalie&$FFFF
	lda.w #$8000
	jsr.w PrintStatHead
	lda.w #$0090
	sta.b $D1
	ldx.w #TxtGA&$FFFF
	lda.w #$8000
	jsr.w PrintStatHead
	lda.w #$00A8
	sta.b $D1
	ldx.w #TxtSh&$FFFF
	lda.w #$8000
	jsr.w PrintStatHead
	lda.w #$00E0
	sta.b $D1
	ldx.w #TxtPtg&$FFFF
	lda.w #$8000
	jmp.w PrintStatHead
